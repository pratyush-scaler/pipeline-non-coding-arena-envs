"""Corpus recovery must use retained bytes without inventing chronology or credit."""
import base64
import hashlib
import json
from pathlib import Path
import tempfile
import unittest

from pipeline.dump import recover, index
from pipeline.ledger import faithfulness
from pipeline.author import extract


class SnapshotRecovery(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory(); self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name) / 'sessions'; self.folder = self.root / 'session'
        (self.folder / 'workspaces').mkdir(parents=True)
        (self.folder / 'files').mkdir()
        self.trace = {'session_id': 'session', 'messages': [
            {'role': 'user', 'node_ids': ['n0'], 'content': []},
            {'role': 'assistant', 'node_ids': ['n1'], 'workspace': 'workspaces/n1.json', 'content': []},
            {'role': 'user', 'node_ids': ['n2'], 'content': []},
            {'role': 'assistant', 'node_ids': ['n3'], 'workspace': 'workspaces/n3.json', 'content': []}],
            'tasks': [{'task_index': 0, 'task_key': 'k', 'n_turns': 4,
                       'turn_ids': ['n0', 'n1', 'n2', 'n3']}]}
        self.snapshot('n1', []); self.snapshot('n3', [])
        self.save()

    def save(self, metadata=None):
        (self.folder / 'data.json').write_text(json.dumps({'traces': [self.trace], 'metadata': metadata or {}}))
        (self.folder / 'outcomes.json').write_text(json.dumps({'outcomes': []}))

    def entry(self, path, content, channel='inline', status='ok'):
        raw = content.encode() if isinstance(content, str) else content
        digest = base64.urlsafe_b64encode(hashlib.sha256(raw).digest()).decode().rstrip('=')
        value = {'path': path, 'hash': digest, 'size': len(raw), 'status': status}
        if channel == 'inline':value['inlineText'] = raw.decode()
        else:
            (self.folder / 'files' / digest).write_bytes(raw)
            if channel == 'explicit':value['file'] = 'files/' + digest
        return value

    def snapshot(self, node, entries):
        (self.folder / 'workspaces' / (node + '.json')).write_text(json.dumps({'files': entries}))

    def workspace(self):return recover.recover(self.trace, self.root)

    def fixture(self, name, raw):
        bundle = self.root.parent / 'bundle'; path = bundle / 'environment/files' / name
        path.parent.mkdir(parents=True, exist_ok=True);path.write_bytes(raw)
        return bundle

    def test_inline_and_both_blob_pointer_forms_are_recovered_verbatim(self):
        expected = {'a.md': 'α\r\nline\r\n', 'b.csv': 'x,y\n1,2\n', 'c.txt': 'generated by a shell command\n'}
        self.snapshot('n1', [self.entry(n, t, c) for (n,t),c in zip(expected.items(), ('inline','explicit','implicit'))])
        ws = self.workspace()
        self.assertEqual({p:r.content for p,r in ws.at(1).items()}, expected)
        self.assertEqual(len(ws.raw_revisions), 3)
        self.assertEqual({r.source for r in ws.revisions}, {'workspace-inline','workspace-blob'})

    def test_later_snapshot_is_not_available_before_its_message(self):
        self.snapshot('n1', [self.entry('draft.md', 'before')])
        self.snapshot('n3', [self.entry('draft.md', 'after')])
        ws = self.workspace()
        self.assertEqual(ws.at(0), {})
        self.assertEqual(ws.at(2)['draft.md'].content, 'before')
        self.assertEqual(ws.at(3)['draft.md'].content, 'after')

    def test_snapshot_poststate_wins_over_tool_body_in_same_message(self):
        self.trace['messages'][1]['content'] = [{'type':'tool-write_file','input':{'path':'/home/user/a.md','content':'intent'}}]
        self.snapshot('n1', [self.entry('home/user/a.md', 'poststate')])
        ws = self.workspace()
        self.assertEqual(ws.paths(), {'home/user/a.md'})
        self.assertEqual(ws.at(1)['home/user/a.md'].content, 'poststate')
        self.assertEqual(len(ws.history('/home/user/a.md')), 2)

    def test_empty_inline_file_is_real_evidence(self):
        self.snapshot('n1', [self.entry('empty.txt', '')])
        self.assertEqual(self.workspace().at(1)['empty.txt'].content, '')

    def test_disappearing_snapshot_path_is_not_resurrected(self):
        self.snapshot('n1', [self.entry('removed.md', 'old')])
        ws = self.workspace()
        self.assertIn('removed.md', ws.at(2));self.assertNotIn('removed.md', ws.at(3))
        self.assertIn('removed.md', ws.span(0,3))
        self.assertEqual(ws.history('removed.md')[0].content, 'old')

    def test_dropped_final_record_invalidates_old_body_even_when_blob_exists(self):
        self.snapshot('n1', [self.entry('private.md', 'old')])
        self.snapshot('n3', [self.entry('private.md', 'withheld', 'implicit', 'dropped:pii')])
        ws = self.workspace()
        self.assertNotIn('private.md', ws.at(3))
        self.assertNotIn('withheld', [r.content for r in ws.revisions])
        self.assertIn('snapshot_dropped:pii', {x['reason'] for x in ws.omissions})

    def test_missing_blob_is_a_recovery_gap_not_empty_content(self):
        entry = self.entry('absent.md','text','implicit');(self.folder/'files'/entry['hash']).unlink()
        self.snapshot('n1',[entry]);ws=self.workspace()
        self.assertEqual(ws.at(1),{})
        self.assertIn('missing_or_unsafe_snapshot_body',{x['reason'] for x in ws.omissions})

    def test_blob_path_escape_is_rejected(self):
        entry=self.entry('a.md','text','explicit');entry['file']='../secret.txt'
        self.snapshot('n1',[entry]);ws=self.workspace()
        self.assertFalse(ws.revisions)
        self.assertIn('missing_or_unsafe_snapshot_body',{x['reason'] for x in ws.omissions})

    def test_blob_symlink_escape_is_rejected(self):
        entry=self.entry('a.md','text','implicit');p=self.folder/'files'/entry['hash'];p.unlink()
        outside=self.root.parent/'outside';outside.write_text('text');p.symlink_to(outside)
        self.snapshot('n1',[entry]);self.assertFalse(self.workspace().revisions)

    def test_output_path_escape_cannot_be_materialised(self):
        self.snapshot('n1',[self.entry('../escape.md','text')]);ws=self.workspace()
        self.assertFalse(ws.revisions)
        self.assertIn('unsafe_snapshot_path',{x['reason'] for x in ws.omissions})

    def test_duplicate_paths_do_not_pick_a_hidden_winner(self):
        self.snapshot('n1',[self.entry('a.md','one'),self.entry('/a.md','two')])
        ws=self.workspace();self.assertFalse(ws.revisions)
        self.assertIn('duplicate_snapshot_path',{x['reason'] for x in ws.omissions})

    def test_unanchored_snapshot_is_quarantined(self):
        self.snapshot('future',[self.entry('answer.md','future answer')])
        ws=self.workspace();self.assertFalse(ws.revisions)
        self.assertIn('unmapped_workspace_snapshot',{x['reason'] for x in ws.omissions})

    def test_manifest_node_fallback_has_exact_message_time(self):
        self.trace['messages'][1].pop('workspace');self.trace['messages'][1]['manifest_node_id']='manifest'
        self.snapshot('manifest',[self.entry('node.md','anchored')])
        ws=self.workspace();self.assertNotIn('node.md',ws.at(0))
        self.assertEqual(ws.at(1)['node.md'].content,'anchored')

    def test_ambiguous_node_fallback_cannot_leak_a_later_state(self):
        for i in (1,3):self.trace['messages'][i]['node_ids'].append('shared')
        self.snapshot('shared',[self.entry('later.md','unknown-time state')])
        ws=self.workspace();self.assertNotIn('later.md',ws.paths())
        self.assertIn('ambiguous_workspace_anchor',{x['reason'] for x in ws.omissions})

    def test_original_digest_mismatch_without_masking_declaration_is_rejected(self):
        entry=self.entry('a.md','original');entry['inlineText']='modified'
        self.snapshot('n1',[entry]);ws=self.workspace();self.assertFalse(ws.revisions)
        self.assertIn('snapshot_integrity_mismatch',{x['reason'] for x in ws.omissions})

    def test_upstream_masked_body_is_bound_to_supplied_bytes(self):
        entry=self.entry('a.md','original');entry['inlineText']='[PERSON_NAME]'
        self.snapshot('n1',[entry]);self.save({'pii_redaction':{'applied':True}})
        ws=self.workspace();self.assertEqual(ws.at(1)['a.md'].content,'[PERSON_NAME]')
        self.assertFalse(ws.declaration_differences[0]['hash_matches'])
        self.assertIn('workspaces/n1.json',ws.recovery_inputs)

    def test_redacted_binary_remains_available_without_claiming_text_readability(self):
        self.snapshot('n1',[self.entry('plot.pdf',b'%PDF-1.7\x00binary','implicit','redacted')])
        ws=self.workspace();self.assertFalse(ws.revisions)
        self.assertEqual(len(ws.raw_revisions),1);self.assertFalse(ws.raw_revisions[0]['text_recovered'])
        self.assertFalse(ws.omissions)

    def test_retained_binary_gets_exact_credit_but_new_binary_does_not(self):
        raw=b'%PDF-1.7\x00document';self.snapshot('n1',[self.entry('report.pdf',raw,'implicit')])
        bundle=self.fixture('report.pdf',raw);self.fixture('invented.pdf',b'%PDF-new')
        ledger=faithfulness.build(bundle,'session',root=self.root);rows={x['path']:x for x in ledger['entries']}
        self.assertEqual(rows['report.pdf']['origin'],'lifted')
        self.assertEqual(rows['invented.pdf']['origin'],'authored')
        self.assertIn('workspaces/n1.json',ledger['source']['recovery_inputs'])

    def test_snapshot_text_changes_source_credit_and_binds_blob_bytes(self):
        raw='snapshot-only text\r\n'.encode();entry=self.entry('source.md',raw,'implicit')
        self.snapshot('n1',[entry]);bundle=self.fixture('source.md',raw)
        before=faithfulness.build(bundle,'session',root=self.root)
        self.assertEqual(before['faithfulness_by_bytes'],1)
        self.assertIn('files/'+entry['hash'],before['source']['recovery_inputs'])
        (self.folder/'files'/entry['hash']).write_bytes(b'changed')
        after=faithfulness.build(bundle,'session',root=self.root)
        self.assertNotEqual(before['source'],after['source'])
        self.assertEqual(after['entries'][0]['origin'],'authored')

    def test_utf8_byte_counts_and_binary_availability_are_distinct(self):
        self.snapshot('n1',[self.entry('a.md','α'*2500),self.entry('report.pdf',b'%PDF\x00binary','implicit')])
        # Keep the same documents in the end-state so a genuine deletion does
        # not remove them from this seed's availability inventory.
        self.snapshot('n3',json.loads((self.folder/'workspaces/n1.json').read_text())['files'])
        self.save();row=index.index_session('session',self.root)[0]
        self.assertEqual(row['deliv_bytes'],5000)
        self.assertEqual(row['deliv_paths'],1)
        self.assertEqual(row['retained_binary_paths'],1)
        self.assertEqual(row['retained_snapshot_versions'],2)

    def test_extraction_does_not_overwrite_distinct_paths_with_same_clean_name(self):
        files=[self.entry('home/user/report.md','one'),self.entry('app/report.md','two')]
        self.snapshot('n1',files);self.snapshot('n3',files);self.save()
        result=extract.extract('session',0,self.root)
        self.assertEqual({d.path:d.content for d in result.before},
                         {'home/user/report.md':'one','app/report.md':'two'})
        self.assertTrue(result.stats['canonical_paths_preserved_to_avoid_collision'])

    def test_retained_non_utf8_text_bytes_are_not_mislabelled_as_authored(self):
        raw='A retained UTF-16 document'.encode('utf-16')
        self.snapshot('n1',[self.entry('source.txt',raw,'implicit')]);bundle=self.fixture('source.txt',raw)
        ledger=faithfulness.build(bundle,'session',root=self.root)
        self.assertEqual(ledger['entries'][0]['origin'],'lifted')

    def test_index_identity_changes_when_equal_length_source_bytes_change(self):
        self.snapshot('n1',[self.entry('a.md','one')]);self.save()
        before=index.index_session('session',self.root)[0]['source_evidence_sha256']
        self.snapshot('n1',[self.entry('a.md','two')])
        after=index.index_session('session',self.root)[0]['source_evidence_sha256']
        self.assertNotEqual(before,after)

    def test_source_availability_survives_later_deletion_without_restoring_live_state(self):
        self.snapshot('n1',[self.entry('draft.md','A'*4500)])
        self.save();ws=self.workspace();row=index.index_session('session',self.root)[0]
        self.assertEqual(ws.at(3),{})
        self.assertEqual(row['deliv_paths'],1)
        self.assertEqual(row['deliv_bytes'],4500)


if __name__ == '__main__':unittest.main()
