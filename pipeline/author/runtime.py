"""The evaluator runtime a bundle ships, staged from one list in one place.

Two copies ship in every bundle: `tests/_arena_runtime/` for the verifier and
`steps/*/solution/_arena_runtime/` for the reference solution. They were
written by two helpers from two lists, and two delivered bundles carried a
solution runtime that differed from the tests runtime -- a reference computed
by one evaluator and graded by another. The exported-grader audit in
`evaluate.py` kept a third list. Now all three read `FILES`.
"""
from __future__ import annotations

import shutil
from pathlib import Path

PACKAGE = "_arena_runtime"
INIT = '"""Self-contained grader runtime generated by the Arena builder."""\n'

#: (module in pipeline/author, name it ships under). `checks_runtime` imports
#: its helpers relatively (`from .contracts import ...`), so they ship as a
#: package, never flat.
FILES = (("checks.py", "checks_runtime.py"), ("oracle.py", "oracle.py"),
         ("contracts.py", "contracts.py"), ("path_witness.py", "path_witness.py"),
         ("subset_witness.py", "subset_witness.py"))

SOURCE = Path(__file__).resolve().parent


def expected() -> dict[str, bytes]:
    """Every file of a current runtime package, relative to its directory."""
    out = {"__init__.py": INIT.encode("utf-8")}
    for origin, shipped in FILES:
        out[shipped] = (SOURCE / origin).read_bytes()
    return out


def stage(dest: Path) -> Path:
    """Replace `dest` with a fresh runtime package. Returns `dest`."""
    dest = Path(dest)
    if dest.is_symlink() or dest.is_file():
        dest.unlink()
    elif dest.is_dir():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    for rel, content in expected().items():
        (dest / rel).write_bytes(content)
    return dest


def problems(bundle: Path) -> list[str]:
    """Every shipped runtime copy is byte-identical to the current generator.

    A copy that differs from the generator is stale; a solution copy that
    differs from the tests copy derives its answer with a different evaluator
    than the one that grades it.
    """
    bundle = Path(bundle)
    want = expected()
    copies = [bundle / "tests" / PACKAGE] + sorted(bundle.glob(f"steps/*/solution/{PACKAGE}"))
    issues = []
    if not copies[0].is_dir():
        issues.append(f"tests/{PACKAGE} is missing")
    for copy in copies:
        if not copy.is_dir():
            continue
        rel = copy.relative_to(bundle).as_posix()
        have = {p.relative_to(copy).as_posix(): p.read_bytes()
                for p in copy.rglob("*") if p.is_file() and "__pycache__" not in p.parts}
        for name in sorted(set(want) | set(have)):
            if name not in have:
                issues.append(f"{rel}/{name} is missing")
            elif name not in want:
                issues.append(f"{rel}/{name} is not part of the generated runtime")
            elif have[name] != want[name]:
                issues.append(f"{rel}/{name} differs from the current generator; rebuild")
    return issues
